<?php
// Run: php extensions.php   (creates badge.png and archive.zip in the current folder)

// 1-2. Which extensions are loaded?
$required = ['intl', 'gd', 'zip'];
foreach ($required as $ext) {
    echo $ext . ': ' . (extension_loaded($ext) ? 'OK' : 'MISSING') . PHP_EOL;
}

$missing = array_filter($required, fn($ext) => !extension_loaded($ext));
if ($missing) {
    exit('Enable the missing extensions, then run again.' . PHP_EOL);
}

// 3a. intl: localized currency formatting
$amount = 1234567.891;
$fr = new NumberFormatter('fr_FR', NumberFormatter::CURRENCY);
$us = new NumberFormatter('en_US', NumberFormatter::CURRENCY);
echo $fr->formatCurrency($amount, 'EUR') . PHP_EOL;   // 1 234 567,89 € (with non-breaking spaces)
echo $us->formatCurrency($amount, 'EUR') . PHP_EOL;   // €1,234,567.89

// 3b. gd: generate an image
$img = imagecreatetruecolor(200, 100);
$background = imagecolorallocate($img, 79, 70, 229);   // indigo
$white = imagecolorallocate($img, 255, 255, 255);
imagefill($img, 0, 0, $background);
imagestring($img, 5, 40, 40, 'PHP rocks!', $white);    // font 5 = largest built-in font
imagepng($img, __DIR__ . '/badge.png');
echo 'badge.png created' . PHP_EOL;

// 3c. zip: build an archive
$zip = new ZipArchive();
if ($zip->open(__DIR__ . '/archive.zip', ZipArchive::CREATE | ZipArchive::OVERWRITE) !== true) {
    exit('Cannot create archive.zip' . PHP_EOL);
}
$zip->addFile(__DIR__ . '/badge.png', 'badge.png');
$zip->addFromString('readme.txt', 'Generated by PHP on ' . date('d/m/Y H:i'));
$zip->close();
echo 'archive.zip created (' . filesize(__DIR__ . '/archive.zip') . ' bytes)' . PHP_EOL;
